// ============================================================
// FLATTEN ALL ROLES
// ============================================================

export const ALL_CAREER_ROLES = CAREER_CATEGORIES.flatMap(
    (category) =>
        category.roles.map((role) => ({
            ...role,
            categoryId: category.id,
            categoryLabel: category.label,
            categoryIcon: category.icon
        }))
);


// ============================================================
// ROLE NAMES ONLY
// Useful for selects, filters and APIs
// ============================================================

export const CAREER_ROLE_NAMES = ALL_CAREER_ROLES.map(
    (role) => role.name
);


// ============================================================
// FIND ROLE
// ============================================================

export const getCareerByName = (roleName) => {
    if (!roleName) {
        return null;
    }

    return (
        ALL_CAREER_ROLES.find(
            (role) =>
                role.name.toLowerCase() ===
                String(roleName).toLowerCase()
        ) || null
    );
};


// ============================================================
// FIND CATEGORY
// ============================================================

export const getCareerCategory = (roleName) => {
    const role = getCareerByName(roleName);

    if (!role) {
        return null;
    }

    return CAREER_CATEGORIES.find(
        (category) => category.id === role.categoryId
    );
};


// ============================================================
// FIND SKILLS
// ============================================================

export const getCareerSkills = (roleName) => {
    const role = getCareerByName(roleName);

    return role?.skills || [];
};


// ============================================================
// CHECK ROLE
// ============================================================

export const isValidCareerRole = (roleName) => {
    return Boolean(getCareerByName(roleName));
};